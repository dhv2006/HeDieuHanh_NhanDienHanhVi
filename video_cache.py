"""Prepare platform videos on disk before offline analysis; serve byte ranges.

Downloads are bounded, streamed in 64 KiB chunks, and never exposed as static
files. Only tokens resolved by social_video can start a job.
"""
import atexit
import re
import tempfile
import threading
import time
from pathlib import Path
from urllib.parse import parse_qs, urlsplit
from video_proxy import open_video

MAX_BYTES = 128 * 1024 * 1024
MAX_JOBS = 4  # at most 512 MiB, including in-progress reservations
TTL = 2 * 60 * 60
DEADLINE = 180
LOCK = threading.Lock()
JOBS = {}
SLOTS = threading.BoundedSemaphore(2)
DIRECTORY = tempfile.TemporaryDirectory(prefix='behaviorlens-video-')
atexit.register(DIRECTORY.cleanup)


def snapshot(job):
    return {k: job[k] for k in ('state', 'received', 'total', 'error')}


def start(token, source):
    with LOCK:
        now = time.monotonic()
        for key, old in list(JOBS.items()):
            if old['state'] != 'loading' and old['expires'] <= now:
                old['path'].unlink(missing_ok=True)
                del JOBS[key]
        if token in JOBS:
            return snapshot(JOBS[token])
        if len(JOBS) >= MAX_JOBS or not SLOTS.acquire(blocking=False):
            raise ValueError('Bộ nhớ đệm video đang bận hoặc đầy. Khởi động lại máy chủ để xóa bộ đệm, hoặc tải file lên.')
        # Token is generated by the resolver, never a filesystem path supplied
        # by a request. mkstemp also avoids collisions between jobs.
        try:
            import os
            fd, name = tempfile.mkstemp(dir=DIRECTORY.name)
            os.close(fd)
            job = {'state': 'loading', 'received': 0, 'total': 0, 'error': None,
                   'expires': now + TTL, 'path': Path(name), 'type': 'video/mp4'}
            JOBS[token] = job
            threading.Thread(target=run, args=(job, dict(source)), daemon=True).start()
            return snapshot(job)
        except Exception:
            SLOTS.release()
            raise


def download(job, source):
    deadline = time.monotonic() + DEADLINE
    validator = None
    with job['path'].open('wb') as output:
        for attempt in range(3):
            conn = response = None
            try:
                if time.monotonic() >= deadline:
                    raise TimeoutError()
                offset = job['received']
                conn, response = open_video(source['url'], f'bytes={offset}-' if offset else None, source.get('headers'))
                if response.status not in (200, 206):
                    raise ValueError('Nguồn video từ nền tảng không đọc được. Mở lại URL hoặc tải file lên.')
                if response.status == 206:
                    match = re.fullmatch(r'bytes (\d+)-(\d+)/(\d+)', response.getheader('Content-Range', ''))
                    if not match or int(match[1]) != offset or int(match[2]) != int(match[3]) - 1:
                        raise ValueError('Nguồn video trả về khoảng dữ liệu không hợp lệ.')
                    total = int(match[3])
                else:
                    if offset:
                        raise ValueError('Nguồn video không hỗ trợ tải tiếp. Mở lại URL hoặc tải file lên.')
                    total = int(response.getheader('Content-Length', '0'))
                if not 0 < total <= MAX_BYTES:
                    raise ValueError('Cần video có dung lượng xác định, tối đa 128 MB. Với video lớn hơn, hãy tải file lên.')
                if job['total'] and job['total'] != total:
                    raise ValueError('Nguồn video đã thay đổi khi tải. Hãy mở lại URL.')
                etag = response.getheader('ETag') or response.getheader('Last-Modified')
                if validator and etag != validator:
                    raise ValueError('Nguồn video đã thay đổi khi tải. Hãy mở lại URL.')
                validator = etag
                with LOCK:
                    job['total'] = total
                    job['type'] = response.getheader('Content-Type', 'video/mp4')
                while job['received'] < total:
                    if time.monotonic() >= deadline:
                        raise TimeoutError()
                    chunk = response.read1(min(64 * 1024, total - job['received']))
                    if not chunk:
                        raise OSError('incomplete body')
                    output.write(chunk)
                    with LOCK:
                        job['received'] += len(chunk)
                output.flush()
                return
            except (OSError, TimeoutError):
                if attempt == 2 or time.monotonic() >= deadline:
                    raise ValueError('Tải video bị gián đoạn sau 3 lần thử hoặc quá 3 phút. Kiểm tra kết nối, mở lại URL hoặc tải file lên.') from None
            finally:
                if response:
                    response.close()
                if conn:
                    conn.close()


def run(job, source):
    try:
        download(job, source)
        with LOCK:
            job['state'] = 'ready'
            job['expires'] = time.monotonic() + TTL
    except Exception as err:
        job['path'].unlink(missing_ok=True)
        with LOCK:
            job['state'] = 'error'
            # Network exception strings can contain signed URLs. Only report
            # controlled validation messages, never raw connection details.
            job['error'] = str(err) if isinstance(err, ValueError) else 'Không chuẩn bị được video. Mở lại URL hoặc tải file lên.'
            job['expires'] = time.monotonic() + 30
    finally:
        SLOTS.release()


def prepare_request(handler):
    if not handler._proxy_allowed():
        return handler._json(403, {'error': 'Máy chủ chỉ phục vụ máy này và mạng nội bộ.'})
    token = (parse_qs(urlsplit(handler.path).query).get('token') or [''])[0]
    try:
        if handler.command == 'POST':
            from social_video import SOURCES, LOCK as SOURCE_LOCK
            with SOURCE_LOCK:
                source = SOURCES.get(token)
                if not source or source['expires'] <= time.monotonic():
                    return handler._json(410, {'error': 'Nguồn video hết hạn. Hãy mở lại URL.'})
                source = dict(source)
            state = start(token, source)
        else:
            with LOCK:
                job = JOBS.get(token)
                if not job or job['expires'] <= time.monotonic():
                    return handler._json(410, {'error': 'Bộ đệm video hết hạn. Hãy mở lại URL.'})
                state = snapshot(job)
        return handler._json(200, state)
    except ValueError as err:
        return handler._json(422, {'error': str(err)})
    except OSError:
        return handler._json(503, {'error': 'Không ghi được bộ đệm video trên máy chủ.'})


def serve(handler, token):
    if not handler._proxy_allowed():
        return handler._json(403, {'error': 'Máy chủ chỉ phục vụ máy này và mạng nội bộ.'})
    with LOCK:
        job = JOBS.get(token)
        if not job or job['state'] != 'ready' or job['expires'] <= time.monotonic():
            return handler._json(410, {'error': 'Video chưa tải đủ hoặc bộ đệm hết hạn. Mở lại URL.'})
        try:
            stream = job['path'].open('rb')
        except OSError:
            return handler._json(410, {'error': 'Bộ đệm video không còn. Mở lại URL.'})
        job['expires'] = time.monotonic() + TTL
        size, content_type = job['total'], job['type']
    with stream:
        start_byte, end_byte = 0, size - 1
        range_header = handler.headers.get('Range')
        if range_header:
            match = re.fullmatch(r'bytes=(\d*)-(\d*)', range_header)
            if match and (match[1] or match[2]):
                if match[1]:
                    start_byte = int(match[1])
                    end_byte = min(int(match[2]), end_byte) if match[2] else end_byte
                else:
                    start_byte = max(0, size - int(match[2]))
                    if int(match[2]) == 0:
                        start_byte = size
            else:
                start_byte = size
            if start_byte > end_byte:
                handler.send_response(416)
                handler.send_header('Content-Range', f'bytes */{size}')
                handler.send_header('Content-Length', '0')
                handler.end_headers()
                return
        handler.send_response(206 if range_header else 200)
        handler.send_header('Content-Type', content_type)
        handler.send_header('Accept-Ranges', 'bytes')
        handler.send_header('Content-Length', str(end_byte - start_byte + 1))
        if range_header:
            handler.send_header('Content-Range', f'bytes {start_byte}-{end_byte}/{size}')
        handler.end_headers()
        stream.seek(start_byte)
        remaining = end_byte - start_byte + 1
        try:
            while remaining:
                chunk = stream.read(min(64 * 1024, remaining))
                if not chunk:
                    break
                handler.wfile.write(chunk)
                remaining -= len(chunk)
        except (BrokenPipeError, ConnectionResetError):
            pass
